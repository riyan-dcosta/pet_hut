create table if not exists public.products (
  id text primary key,
  name text not null,
  brand text not null,
  category text not null check (category in ('dog_food', 'cat_food', 'treats', 'combos')),
  description text not null,
  price_rupees numeric(12, 2) not null check (price_rupees >= 0),
  mrp_rupees numeric(12, 2) not null check (mrp_rupees >= price_rupees),
  weight text,
  bundle_product_ids text[] not null default '{}',
  image_url text not null,
  active boolean not null default true,
  offer_ids text[] not null default '{}'
);

create table if not exists public.seasonal_offers (
  id text primary key,
  name text not null,
  description text not null,
  discount_percent numeric(5, 2) not null check (discount_percent > 0 and discount_percent <= 100),
  product_ids text[] not null default '{}',
  starts_at timestamptz,
  ends_at timestamptz,
  enabled boolean not null default false,
  banner_text text not null,
  check (starts_at is null or ends_at is null or starts_at <= ends_at)
);

create table if not exists public.serviceable_pincodes (
  id bigint generated by default as identity primary key,
  start_pincode integer not null check (start_pincode between 100000 and 999999),
  end_pincode integer not null check (end_pincode between start_pincode and 999999),
  state text not null check (state = 'Karnataka'),
  city text not null,
  district text not null,
  serviceable boolean not null default true,
  delivery_days_min integer not null check (delivery_days_min > 0),
  delivery_days_max integer not null check (delivery_days_max >= delivery_days_min),
  unique (start_pincode, end_pincode)
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'placed'
    check (status in ('placed', 'processing', 'shipped', 'delivered', 'cancelled', 'return_requested')),
  items jsonb not null check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) > 0),
  subtotal_rupees numeric(12, 2) not null check (subtotal_rupees >= 0),
  discount_rupees numeric(12, 2) not null check (discount_rupees >= 0),
  total_rupees numeric(12, 2) not null check (total_rupees >= 0),
  address jsonb not null check (jsonb_typeof(address) = 'object'),
  created_at timestamptz not null default now(),
  cancellation_reason text,
  return_reason text
);

create index if not exists orders_user_created_idx on public.orders (user_id, created_at desc);
create index if not exists serviceable_pincodes_range_idx
  on public.serviceable_pincodes (start_pincode, end_pincode)
  where serviceable;

