  from anon, authenticated;
grant select on public.products, public.seasonal_offers, public.serviceable_pincodes
  to anon, authenticated;

drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
  on public.products for select to anon, authenticated using (active);

drop policy if exists "Public can read enabled offers" on public.seasonal_offers;
create policy "Public can read enabled offers"
  on public.seasonal_offers for select to anon, authenticated using (enabled);

drop policy if exists "Public can read serviceable ranges" on public.serviceable_pincodes;
create policy "Public can read serviceable ranges"
  on public.serviceable_pincodes for select to anon, authenticated using (serviceable);

revoke all on public.orders from anon, authenticated;
grant select on public.orders to authenticated;
grant update (status, cancellation_reason, return_reason) on public.orders to authenticated;

drop policy if exists "Users can read their own orders" on public.orders;
create policy "Users can read their own orders"
  on public.orders for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists "Users can update their own order requests" on public.orders;
create policy "Users can update their own order requests"
  on public.orders for update to authenticated
  using (user_id = (select auth.uid()) and status in ('placed', 'processing', 'shipped', 'delivered'))
  with check (
    user_id = (select auth.uid())
    and status in ('placed', 'processing', 'shipped', 'delivered', 'cancelled', 'return_requested')
  );

create or replace function public.protect_order_request_updates()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if current_user <> 'authenticated' then
    return new;
  end if;

  if (to_jsonb(new) - array['status', 'cancellation_reason', 'return_reason'])
     is distinct from
     (to_jsonb(old) - array['status', 'cancellation_reason', 'return_reason']) then
    raise exception 'Order details cannot be changed by customers';
  end if;

  if old.status in ('placed', 'processing', 'shipped')
     and new.status = 'cancelled'
     and nullif(trim(new.cancellation_reason), '') is not null
     and new.cancellation_reason in (
       'Ordered by mistake',
       'Delivery taking too long',
       'Found a better option',
       'Other'
     )
     and new.return_reason is not distinct from old.return_reason then
    return new;
  end if;

  if old.status = 'delivered'
     and new.status = 'return_requested'
     and nullif(trim(new.return_reason), '') is not null
     and new.return_reason in (
       'Item arrived damaged',
       'Wrong item received',
       'Pet did not accept the product',
       'Other'
     )
     and new.cancellation_reason is not distinct from old.cancellation_reason then
    return new;
  end if;

  raise exception 'Invalid order status transition';
end;
$$;

drop trigger if exists protect_order_request_updates on public.orders;
create trigger protect_order_request_updates
  before update on public.orders
  for each row execute function public.protect_order_request_updates();

create or replace function public.place_pet_hut_order(p_address jsonb, p_items jsonb)
returns public.orders
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_pincode text := p_address ->> 'pincode';
  v_range public.serviceable_pincodes%rowtype;
  v_product public.products%rowtype;
  v_offer public.seasonal_offers%rowtype;
  v_item jsonb;
  v_quantity integer;
  v_subtotal numeric(12, 2) := 0;
  v_discount numeric(12, 2) := 0;
  v_line_discount numeric(12, 2);
  v_offer_percent numeric(5, 2);
  v_offer_id text;
  v_order_items jsonb := '[]'::jsonb;
  v_address jsonb;
  v_order public.orders%rowtype;
begin
  if v_user_id is null then
    raise exception 'Sign in before placing your order';
  end if;

  if p_address is null or jsonb_typeof(p_address) <> 'object'
     or p_items is null or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0 then
    raise exception 'An address and at least one cart item are required';
  end if;

  if coalesce(trim(p_address ->> 'name'), '') = ''
     or coalesce(trim(p_address ->> 'phone'), '') = ''
     or trim(p_address ->> 'phone') !~ '^\+91[6-9][0-9]{9}$'
     or coalesce(trim(p_address ->> 'street'), '') = ''
     or coalesce(trim(p_address ->> 'city'), '') = ''
     or coalesce(trim(p_address ->> 'district'), '') = ''
     or v_pincode !~ '^[0-9]{6}$' then
    raise exception 'Complete all required delivery details';
  end if;

  select * into v_range
  from public.serviceable_pincodes
  where serviceable
    and v_pincode::integer between start_pincode and end_pincode
  limit 1;
  if not found then
    raise exception 'Pincode is not serviceable';
  end if;

  if lower(trim(p_address ->> 'city')) <> lower(v_range.city)
     or lower(trim(p_address ->> 'district')) <> lower(v_range.district) then
    raise exception 'City and district must match the serviceable pincode';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if jsonb_typeof(v_item) <> 'object'
       or (v_item ->> 'productId') is null
       or (v_item ->> 'quantity') !~ '^[0-9]+$' then
      raise exception 'Cart item is invalid';
    end if;

    v_quantity := (v_item ->> 'quantity')::integer;
    if v_quantity < 1 or v_quantity > 99 then
      raise exception 'Cart quantity must be between 1 and 99';
    end if;

    select * into v_product
    from public.products
    where id = v_item ->> 'productId' and active;
    if not found then
      raise exception 'A cart product is no longer available';
    end if;

    v_offer_percent := 0;
    v_offer_id := null;
    select * into v_offer
    from public.seasonal_offers
    where enabled
      and product_ids @> array[v_product.id]
      and (starts_at is null or starts_at <= now())
      and (ends_at is null or ends_at >= now())
    order by discount_percent desc
    limit 1;
    if found then
      v_offer_percent := v_offer.discount_percent;
      v_offer_id := v_offer.id;
    end if;

    v_line_discount := round(v_product.price_rupees * v_offer_percent / 100, 2);
    v_subtotal := v_subtotal + v_product.price_rupees * v_quantity;
    v_discount := v_discount + v_line_discount * v_quantity;
    v_order_items := v_order_items || jsonb_build_array(jsonb_build_object(
      'productId', v_product.id,
      'name', v_product.name,
      'quantity', v_quantity,
      'unitPriceRupees', v_product.price_rupees - v_line_discount,
      'offerId', v_offer_id
    ));
  end loop;

  v_address := jsonb_build_object(
    'name', trim(p_address ->> 'name'),
    'phone', trim(p_address ->> 'phone'),
    'street', trim(p_address ->> 'street'),
    'city', v_range.city,
    'district', v_range.district,
    'state', 'Karnataka',
    'pincode', v_pincode
  );

  insert into public.orders (
    user_id, status, items, subtotal_rupees, discount_rupees, total_rupees, address
  ) values (
    v_user_id, 'placed', v_order_items, v_subtotal, v_discount,
    v_subtotal - v_discount, v_address
  ) returning * into v_order;

  return v_order;
end;
$$;

revoke all on function public.place_pet_hut_order(jsonb, jsonb) from public, anon, authenticated;
grant execute on function public.place_pet_hut_order(jsonb, jsonb) to authenticated;
